import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('policy-preview')
  await expect(page.getByRole('heading', { name: '정책 · 룰셋 관리' })).toBeVisible()
})

test('policy list, detail, sources and timeline render without API network requests', async ({ page }) => {
  const requests: string[] = []
  page.on('request', (request) => {
    if (new URL(request.url()).pathname.startsWith('/api/')) requests.push(request.url())
  })
  await page.screenshot({ path: 'test-results/policy-ui-722/01-list.png', fullPage: true })
  await page.getByRole('button', { name: '선택 정책 관리' }).click()
  await expect(page.getByRole('heading', { name: '7년 분급 수수료 정책', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '초안 수정' })).toBeEnabled()
  await page.screenshot({ path: 'test-results/policy-ui-722/02-detail.png', fullPage: true })
  await page.getByRole('tab', { name: '근거 자료', exact: true }).click()
  await expect(page.getByText('화면 검토용 예시 근거')).toBeVisible()
  await expect(page.getByText(/법정 심의·의결을 대체하지 않습니다/)).toBeVisible()
  await expect(page.getByLabel('근거 상태', { exact: true })).toHaveText('회사정책')
  await page.screenshot({ path: 'test-results/policy-ui-722/07-sources.png', fullPage: true })
  await page.getByRole('tab', { name: '승인 이력', exact: true }).click()
  await expect(page.getByText('화면 검토용 예시 초안 작성')).toBeVisible()
  expect(requests).toEqual([])
})

test('source status tags can be edited and persist in the preview detail', async ({ page }) => {
  await page.getByRole('button', { name: '선택 정책 관리' }).click()
  await page.getByRole('button', { name: '초안 수정' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: /근거 자료/ }).click()
  await dialog.getByRole('checkbox', { name: 'FAQ', exact: true }).check()
  await page.screenshot({ path: 'test-results/policy-ui-722/08-source-editor.png', fullPage: true })
  await dialog.getByRole('button', { name: '초안 저장' }).click()
  await page.getByRole('tab', { name: '근거 자료', exact: true }).click()
  await expect(page.getByLabel('근거 상태', { exact: true })).toContainText('FAQ')
  await expect(page.getByLabel('근거 상태', { exact: true })).toContainText('회사정책')
})

test('draft creation, field focus and unsaved changes preserve the selected policy', async ({ page }) => {
  await page.getByRole('button', { name: '정책 등록', exact: false }).click()
  await page.getByRole('button', { name: '초안 저장' }).click()
  await expect(page.getByRole('dialog').getByLabel('정책코드')).toBeFocused()
  await page.getByRole('dialog').getByLabel('정책코드').fill('UI-CREATED')
  await page.getByRole('dialog').getByLabel('정책명').fill('신규 정책 화면 검토')
  await page.getByRole('dialog').getByLabel('정책 유형').selectOption('SEVEN_YEAR_COMMISSION')
  await page.getByRole('dialog').getByLabel('출처 분류').selectOption('GA_POLICY')
  await page.getByRole('dialog').getByLabel('적용 시작일').fill('2029-01-01')
  await page.screenshot({ path: 'test-results/policy-ui-722/03-create.png', fullPage: true })
  await page.getByRole('button', { name: '취소', exact: true }).click()
  await page.getByRole('button', { name: '계속 편집' }).click()
  await expect(page.getByRole('dialog').getByLabel('정책명')).toHaveValue('신규 정책 화면 검토')
  await page.getByRole('button', { name: '초안 저장' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('heading', { name: '신규 정책 화면 검토', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '초안 수정' }).click()
  await expect(page.getByRole('dialog').getByLabel('정책코드')).toBeDisabled()
  await page.getByRole('button', { name: /분급 룰셋/ }).click()
  await page.getByRole('button', { name: '분급 룰셋 추가' }).click()
  await expect(page.getByRole('dialog').getByLabel('장기유지 시작 회차')).toHaveValue('')
  await expect(page.getByRole('dialog').getByLabel('장기유지 끝 회차')).toHaveValue('')
})

test('RATE and FIXED switch exclusively, and seven-year rules validate the exact row', async ({ page }) => {
  await page.getByRole('button', { name: '선택 정책 관리' }).click()
  await page.getByRole('button', { name: '초안 수정' }).click()
  await page.getByRole('button', { name: /수수료 규칙/ }).click()
  await expect(page.getByRole('dialog').getByLabel('고정금액 (원)')).toBeDisabled()
  await page.getByRole('dialog').getByLabel('요율 (%)').fill('650.123456')
  await page.getByRole('dialog').getByLabel('계산 방식').selectOption('FIXED')
  await expect(page.getByRole('dialog').getByLabel('요율 (%)')).toBeDisabled()
  await expect(page.getByRole('dialog').getByLabel('요율 (%)')).toHaveValue('')
  await page.getByRole('dialog').getByLabel('고정금액 (원)').fill('12000')
  await page.screenshot({ path: 'test-results/policy-ui-722/04-rule-editor.png', fullPage: true })
  await page.getByRole('button', { name: /분급 룰셋/ }).click()
  await page.getByRole('dialog').getByLabel('최대 회차').fill('85')
  await page.getByRole('button', { name: '초안 저장' }).click()
  await expect(page.getByRole('dialog').getByLabel('최대 회차')).toBeFocused()
  await expect(page.getByText('1~84회차 사이로 입력하세요.')).toBeVisible()
  await page.getByRole('dialog').getByLabel('최대 회차').fill('84')
  await page.getByRole('button', { name: '초안 저장' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByText('12,000원', { exact: true })).toBeVisible()
})

test('approval requires a reason, activation is separate, and new version selects a fresh draft', async ({ page }) => {
  await page.getByRole('radio', { name: 'UI-STATUS v1 선택' }).click()
  await expect(page.getByRole('radio', { name: 'UI-STATUS v1 선택' })).toBeChecked()
  await page.getByRole('button', { name: '선택 정책 관리' }).click()
  await page.getByRole('button', { name: '승인', exact: true }).click()
  await page.getByRole('button', { name: '승인 확인' }).click()
  await expect(page.getByRole('dialog').getByLabel('작업 사유')).toBeFocused()
  await page.getByRole('dialog').getByLabel('작업 사유').fill('UI 검토를 완료했습니다.')
  await page.screenshot({ path: 'test-results/policy-ui-722/05-approval.png', fullPage: true })
  await page.getByRole('button', { name: '승인 확인' }).click()
  await expect(page.getByRole('button', { name: '활성화', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '초안 수정' })).toHaveCount(0)
  await page.getByRole('button', { name: '새 버전 작성', exact: true }).click()
  await page.getByRole('dialog').getByLabel('새 버전 적용 시작일').fill('2029-02-01')
  await page.getByRole('dialog').getByLabel('작업 사유').fill('다음 적용 기간 검토')
  await page.getByRole('button', { name: '새 초안 만들기' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '초안 수정' })).toBeVisible()
  await expect(page.getByText('VERSION 2', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '제출', exact: true }).click()
  await page.getByRole('dialog').getByLabel('작업 사유').fill('새 버전 검토 요청')
  await page.getByRole('button', { name: '제출 확인' }).click()
  await expect(page.getByRole('button', { name: '승인', exact: true })).toBeDisabled()
  await expect(
    page.getByText('작성자는 본인이 작성한 정책을 승인할 수 없습니다. 다른 승인자의 검토가 필요합니다.'),
  ).toBeVisible()
})

