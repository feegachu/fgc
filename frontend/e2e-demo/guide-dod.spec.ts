import { test, expect, login } from './fixtures'

for (const width of [1440, 390]) {
  test(`CMN-C04 DoD ${width}px: 실제 화면의 배치·키보드·입력 보존·대상 오류 복구`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 900 })
    await login(page, 'audit01', '/schedules')
    const writes: string[] = []
    page.on('request', request => {
      const path = new URL(request.url()).pathname
      if (['POST', 'PUT', 'PATCH', 'DELETE'].includes(request.method()) && path.startsWith('/api/v1/') && !path.startsWith('/api/v1/auth/')) writes.push(path)
    })
    const help = page.locator('.page-header').getByRole('button', { name: '도움말', exact: true })
    await expect(help).toHaveCount(1)
    const input = page.getByLabel('계약번호', { exact: true })
    await input.fill('DOD-KEEP-INPUT')
    await help.focus()
    await page.keyboard.press('Enter')
    const card = page.getByRole('region', { name: '예상 스케줄 목록 도움말', exact: true })
    const spotlight = page.locator('.payment-guide-spotlight')
    await expect(card).toBeVisible()
    await expect(spotlight).toHaveCount(1)
    await expect(card).toContainText(/화면 요소 안내 · 1\/\d+/)
    // Check the actual viewport bounds and input/card overlap after layout settles.
    await expect.poll(async () => {
      const target = await input.boundingBox()
      const coach = await card.boundingBox()
      return Boolean(target && coach && coach.x >= 0 && coach.y >= 0 && coach.x + coach.width <= width + 1 && coach.y + coach.height <= 901 && !(target.x < coach.x + coach.width && target.x + target.width > coach.x && target.y < coach.y + coach.height && target.y + target.height > coach.y))
    }).toBe(true)
    expect(await spotlight.evaluate(element => getComputedStyle(element).transitionDuration)).toBe('0.7s, 0.7s, 0.7s, 0.7s')
    await page.screenshot({ path: info.outputPath('01-layout.png'), fullPage: true })
    await card.getByRole('button', { name: '접기', exact: true }).focus()
    await page.keyboard.press('Enter')
    await expect(spotlight).toHaveCount(0)
    await expect(input).toHaveValue('DOD-KEEP-INPUT')
    await page.screenshot({ path: info.outputPath('02-folded.png'), fullPage: true })
    await card.getByRole('button', { name: '펼치기', exact: true }).click()
    await expect(card).toContainText(/화면 요소 안내 · 1\/\d+/)
    await page.emulateMedia({ reducedMotion: 'reduce' })
    expect(await card.locator('img').evaluate(element => getComputedStyle(element).animationName)).toBe('none')
    expect(await spotlight.evaluate(element => getComputedStyle(element).transitionDuration.split(',').every(value => parseFloat(value) <= 0.001))).toBe(true)
    await page.emulateMedia({ reducedMotion: 'no-preference' })
    expect(await card.locator('img').evaluate(element => getComputedStyle(element).animationDuration)).toBe('3s')

    // Fault injection changes only this browser DOM. A duplicate must stop the
    // guide instead of choosing an arbitrary target or running a business write.
    await page.evaluate(() => {
      const duplicate = document.createElement('div')
      duplicate.dataset.guideTarget = 'schedule.filters'
      duplicate.id = 'dod-duplicate'
      duplicate.style.cssText = 'width:100px;height:40px'
      document.getElementById('main-content')!.append(duplicate)
    })
    await expect(card.getByText(/화면 구성이 바뀌어/)).toBeVisible()
    await expect(spotlight).toHaveCount(0)
    await page.screenshot({ path: info.outputPath('03-duplicate-paused.png'), fullPage: true })
    await page.locator('#dod-duplicate').evaluate(element => element.remove())
    await expect(spotlight).toHaveCount(1)
    await page.locator('[data-guide-target="schedule.filters"]').evaluate(element => { (element as HTMLElement).style.visibility = 'hidden' })
    await expect(card.getByText(/화면 구성이 바뀌어/)).toBeVisible()
    await expect(spotlight).toHaveCount(0)
    await page.locator('[data-guide-target="schedule.filters"]').evaluate(element => { (element as HTMLElement).style.visibility = '' })
    await expect(spotlight).toHaveCount(1)
    await page.locator('[data-guide-target="schedule.filters"]').evaluate(element => element.removeAttribute('data-guide-target'))
    await expect(card.getByText(/화면 구성이 바뀌어/)).toBeVisible()
    await expect(spotlight).toHaveCount(0)
    await page.screenshot({ path: info.outputPath('04-missing-target.png'), fullPage: true })
    await page.locator('.schedule-filter-bar').evaluate(element => element.setAttribute('data-guide-target', 'schedule.filters'))
    await expect(spotlight).toHaveCount(1)
    await expect(input).toHaveValue('DOD-KEEP-INPUT')
    await card.getByRole('button', { name: '다음', exact: true }).click()
    await expect(card).toContainText(/화면 요소 안내 · 2\/\d+/)
    await card.getByRole('button', { name: '이전', exact: true }).click()
    await expect(card).toContainText(/화면 요소 안내 · 1\/\d+/)
    await card.getByRole('button', { name: '종료', exact: true }).click()
    await expect(help).toBeFocused()
    await expect(input).toHaveValue('DOD-KEEP-INPUT')
    await help.click()
    await expect(card).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(card).toHaveCount(0)
    await expect(help).toBeFocused()
    await page.getByRole('button', { name: '업무 비서 AI 열기, 피코' }).click()
    const pico = page.getByRole('dialog', { name: '피코 업무 비서' })
    await expect(pico).toBeVisible()
    await expect(pico.getByText('현재 보고 있는 업무', { exact: true })).toHaveCount(0)
    await expect(pico.getByText('PICO WORKFLOW ASSISTANT', { exact: true })).toHaveCount(0)
    await expect(page.locator('.launcher-dot,.pico-launcher-dot,.live-dot')).toHaveCount(0)
    await expect(pico.getByText(/^현재 화면 .+, 대상 선택 없음, 기준월 /)).toBeVisible()
    await page.screenshot({ path: info.outputPath('05-service-pico-cleanup.png'), fullPage: true })
    await pico.getByRole('button', { name: '비서 닫기', exact: true }).click()
    await expect(input).toHaveValue('DOD-KEEP-INPUT')
    expect(writes).toEqual([])
  })
}
