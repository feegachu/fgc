import type { ScreenHelpStep } from './ScreenHelp'

type Copy = [title: string, instruction: string, interaction: string]
  | [title: string, instruction: string, detail: string, interaction: string]
const target = (targetId: string, ...copy: Copy): ScreenHelpStep => ({
  targetId, anchor: 'start', title: copy[0], instruction: copy[1], group: '',
  concise: copy.length === 3,
  details: copy.length === 4 ? [{ label: '확인할 점', text: copy[2] }] : [],
  interaction: copy.length === 4 ? copy[3] : copy[2],
})
const region = (id: string, selector: string, ...copy: Copy): ScreenHelpStep => ({ ...target(id, ...copy), selector })
const heading = (id: string, ...copy: Copy) => region(id, `[aria-labelledby="${id}"]`, ...copy)
const feature = (id: string, ...copy: Copy): ScreenHelpStep => ({ ...target(id, ...copy), attribute: 'data-guide-feature' })
const tour = (group: string, ...steps: ScreenHelpStep[]) => steps.map(step => ({ ...step, group }))
const contractInputTour = (...steps: ScreenHelpStep[]) => tour('보험계약 입력', ...steps).map(step => {
  const field = step.targetId.split('.').at(-1)
  const select = ['insurer-id', 'product-offering-id', 'contract-status', 'next-contract-status', 'contract-date'].includes(field ?? '')
  return { ...step, anchor: undefined,
    presentation: { side: (step.targetId === 'contract-agent-heading' ? 'above'
      : step.targetId === 'contract-premium-heading' || step.targetId === 'contract.limitPreview' || step.targetId === 'contract.save' ? 'left' : 'right') as 'above' | 'left' | 'right', includeLabel: true },
    openControl: select || step.targetId === 'contract-agent-heading',
    advanceOnSelection: select || step.targetId === 'contract-agent-heading',
  }
})

